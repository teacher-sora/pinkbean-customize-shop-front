do $do$
declare s text;
begin
  foreach s in array array['public', 'plaza_dev'] loop
    execute format($f$
      create table if not exists %1$I.plaza_alias (
        owner uuid primary key references auth.users(id) on delete cascade,
        alias text not null unique,
        created_at timestamptz not null default now()
      );
      alter table %1$I.plaza_alias enable row level security;
      drop policy if exists "alias read" on %1$I.plaza_alias;
      create policy "alias read" on %1$I.plaza_alias for select to anon, authenticated using (true);
      revoke all on %1$I.plaza_alias from anon, authenticated;
      grant select on %1$I.plaza_alias to anon, authenticated;

      -- 이름 정하기. 이미 있으면 그대로 돌려준다. 없으면 want(아무도 안 쓰는 때만), 그다음은 무작위.
      create or replace function %1$I.plaza_alias_ensure(u uuid, want text default null) returns text
      language plpgsql security definer set search_path = '' as $$
      declare a text; adj text[] := plaza_priv.alias_adj(); noun text[] := plaza_priv.alias_noun(); i int;
      begin
        if u is null then return null; end if;
        select alias into a from %1$I.plaza_alias where owner = u;
        if a is not null then return a; end if;
        if want is not null then
          insert into %1$I.plaza_alias(owner, alias) values (u, want) on conflict do nothing returning alias into a;
          if a is not null then return a; end if;
        end if;
        for i in 1..200 loop
          a := adj[1 + floor(random() * array_length(adj, 1))::int] || ' ' || noun[1 + floor(random() * array_length(noun, 1))::int];
          insert into %1$I.plaza_alias(owner, alias) values (u, a) on conflict do nothing returning alias into a;
          if a is not null then return a; end if;
          select alias into a from %1$I.plaza_alias where owner = u;   -- 같은 사람이 동시에 들어온 경우
          if a is not null then return a; end if;
        end loop;
        raise exception 'plaza alias: 빈 이름을 찾지 못했다(낱말을 늘릴 때)';
      end $$;
      revoke all on function %1$I.plaza_alias_ensure(uuid, text) from public, anon, authenticated;

      create or replace function %1$I.plaza_alias_touch() returns trigger
      language plpgsql security definer set search_path = '' as $$
      begin
        begin
          perform %1$I.plaza_alias_ensure(new.owner);
        exception when others then null;   -- 이름을 못 정해도 글은 달린다
        end;
        return new;
      end $$;
      drop trigger if exists plaza_comments_alias on %1$I.plaza_comments;
      create trigger plaza_comments_alias after insert on %1$I.plaza_comments for each row execute function %1$I.plaza_alias_touch();
      drop trigger if exists plaza_notice_comments_alias on %1$I.plaza_notice_comments;
      create trigger plaza_notice_comments_alias after insert on %1$I.plaza_notice_comments for each row execute function %1$I.plaza_alias_touch();
    $f$, s);

    -- 옮겨 적기: 먼저 쓴 사람부터 예전 이름을 물려받는다.
    execute format($f$
      do $b$
      declare r record; old text;
      begin
        for r in
          select owner, min(created_at) as first from (
            select owner, created_at from %1$I.plaza_comments
            union all select owner, created_at from %1$I.plaza_notice_comments
          ) t where owner is not null group by owner order by first, owner
        loop
          old := plaza_priv.alias_legacy(r.owner);
          if split_part(old, ' ', 2) <> all (plaza_priv.alias_noun()) then old := null; end if;
          perform %1$I.plaza_alias_ensure(r.owner, old);
        end loop;
      end $b$;
    $f$, s);
  end loop;
end $do$;
